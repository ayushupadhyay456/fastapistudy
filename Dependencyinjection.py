# -------------------------------------------------------------------------
# Standard Library and Typing Imports
# -------------------------------------------------------------------------
# Annotated: Allows adding FastAPI metadata (like Depends) to standard type hints.
# Generator: Type hint for functions using 'yield' (yielded_type, send_type, return_type).
from typing import Annotated, Generator

# -------------------------------------------------------------------------
# FastAPI Framework Imports
# -------------------------------------------------------------------------
# Depends: Marks a parameter as a dependency for FastAPI's DI container to resolve.
# FastAPI: The primary application class used to mount routes and middleware.
# HTTPException: Pre-configured exception class to return standard HTTP error responses.
# status: Provides descriptive HTTP status code constants (e.g., HTTP_201_CREATED).
from fastapi import Depends, FastAPI, HTTPException, status

# -------------------------------------------------------------------------
# Pydantic Schemas & Data Validation Imports
# -------------------------------------------------------------------------
# BaseModel: Base class for building request payload validation and response schemas.
# ConfigDict: Used in Pydantic v2 to define schema-level configuration cleanly.
from pydantic import BaseModel, ConfigDict

# -------------------------------------------------------------------------
# SQLAlchemy Core and ORM Imports
# -------------------------------------------------------------------------
# create_engine: Establishes the database connection pool and dialect handler.
# select: Constructs SQL SELECT statements (preferred syntax in SQLAlchemy 2.0).
from sqlalchemy import create_engine, select

# DeclarativeBase: Modern 2.0 base class factory for ORM models.
# Mapped: Type annotation generic mapping Python types to database column types.
# mapped_column: Defines column attributes, constraints, indices, and defaults.
# Session: The ORM handle managing transactions and persistence.
# sessionmaker: Factory callable for generating new Session instances.
from sqlalchemy.orm import DeclarativeBase, Mapped, Session, mapped_column, sessionmaker

# =========================================================================
# 1. DATABASE CONFIGURATION & ENGINE INITIALIZATION
# =========================================================================

# Connection string pointing to a local SQLite file named 'app.db'
DATABASE_URL = "sqlite:///./app.db"

# create_engine initializes the underlying pool and SQLite driver.
# check_same_thread=False is SQLite-specific: allows FastAPI worker threads
# to interact with SQLite connections across concurrent requests.
engine = create_engine(
    DATABASE_URL, 
    connect_args={"check_same_thread": False}
)

# sessionmaker produces Session objects pre-bound to our engine.
# autocommit=False ensures transactions are explicitly committed via db.commit().
# autoflush=False prevents automatic synchronization before explicit queries.
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

# Base class inheriting from DeclarativeBase to register all ORM models into metadata.
class Base(DeclarativeBase):
    pass

# =========================================================================
# 2. SQLALCHEMY ORM MODEL DEFINITION
# =========================================================================

# Represents the 'users' table in the database
class UserModel(Base):
    # Explicit SQL table name
    __tablename__ = "users"

    # Primary key integer column with an index for rapid retrieval
    id: Mapped[int] = mapped_column(primary_key=True, index=True)

    # Unique, indexed, non-nullable username string
    username: Mapped[str] = mapped_column(unique=True, index=True, nullable=False)

    # Unique, indexed, non-nullable email address string
    email: Mapped[str] = mapped_column(unique=True, index=True, nullable=False)

# Emits DDL statements ('CREATE TABLE IF NOT EXISTS') to SQLite for defined models.
Base.metadata.create_all(bind=engine)

# =========================================================================
# 3. PYDANTIC SCHEMAS (DATA VALIDATION & SERIALIZATION)
# =========================================================================

# Schema validating the incoming JSON body when creating a user
class UserCreate(BaseModel):
    # Requires a valid string payload for username
    username: str
    # Requires a valid string payload for email
    email: str

# Schema formatting and filtering outgoing response payloads
class UserResponse(BaseModel):
    # ID generated by the database
    id: int
    # Serialized username string
    username: str
    # Serialized email string
    email: str

    # Pydantic v2 configuration: enables reading attributes directly from ORM objects
    # (e.g., user.id) instead of requiring a raw dictionary (e.g., user["id"]).
    model_config = ConfigDict(from_attributes=True)

# =========================================================================
# 4. DEPENDENCY INJECTION: DATABASE SESSION LIFECYCLE
# =========================================================================

# Generator dependency managing the creation and guaranteed disposal of DB sessions
def get_db() -> Generator[Session, None, None]:
    # 1. SETUP: Instantiate a new, isolated session for the incoming request
    db = SessionLocal()
    try:
        # 2. YIELD: Injects the active session directly into the route function
        yield db
    finally:
        # 3. TEARDOWN: Runs after the response is sent (or if an unhandled error occurs),
        # returning the connection to the pool and closing open resources.
        db.close()

# Reusable type alias: injects a Session by binding get_db to FastAPI's Depends()
DbSession = Annotated[Session, Depends(get_db)]

# =========================================================================
# 5. FASTAPI APPLICATION & ROUTE DEFINITIONS
# =========================================================================

# Instantiate the FastAPI application with custom OpenAPI documentation metadata
app = FastAPI(title="DB Session Injection Demo")

# POST endpoint: Receives user payload, runs checks, and persists new user
@app.post(
    "/users/", 
    response_model=UserResponse, 
    status_code=status.HTTP_201_CREATED
)
def create_user(user_data: UserCreate, db: DbSession):
    # Build a 2.0 select query filtering by the requested email
    query = select(UserModel).where(UserModel.email == user_data.email)
    
    # Execute the query and fetch the first matching ORM record (or None)
    existing_user = db.scalars(query).first()
    
    # If the email already exists in the database, abort and return a 400 Bad Request
    if existing_user:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, 
            detail="Email already registered"
        )

    # Instantiate the ORM model from the validated Pydantic schema data
    new_user = UserModel(username=user_data.username, email=user_data.email)
    
    # Stage the new instance in the session transaction
    db.add(new_user)
    
    # Commit the transaction to save changes permanently to SQLite
    db.commit()
    
    # Refresh the instance from the DB to populate generated attributes (like user.id)
    db.refresh(new_user)
    
    # Return the ORM instance; FastAPI automatically serializes it using UserResponse
    return new_user

# GET endpoint: Retrieves a specific user by their primary key ID
@app.get("/users/{user_id}", response_model=UserResponse) #Response model only gives the data defined in the class
def read_user(user_id: int, db: DbSession):
    # Query the database directly by primary key
    user = db.get(UserModel, user_id)
    
    # If no record matches the ID, abort with a 404 Not Found error
    if not user:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, 
            detail="User not found"
        )
        
    # Return the user record matching the UserResponse schema
    return user    